NOTRETAIL = ["АМУРСКИЙ ТИГР", "ФКП ЯСЕНЬ", "ПРЕЗИДЕНТ-ОТЕЛЬ", "ЧОП "]
HAS_FORM = re.compile(r"(ООО|OOO|ОАО|ЗАО|АО|ИП|ПБОЮЛ|ЧП|ТОО|ОсОО|ФГУП|ФКП|АНО|ОБЩЕСТВО С ОГРАНИЧЕННОЙ)", re.I)


def classify_entity(name):
    """-> (тип записи, ключ площадки или None)"""
    u = name.upper()
    if name.startswith("_") or any(m in u for m in INTERNAL):
        return "внутренний счёт", None
    if any(m in u for m in STAFF):
        return "сотрудник", None
    if any(m in u for m in LOGISTICS):
        return "логистика (не розница)", None
    if any(m in u for m in NOTRETAIL):
        return "не розница", None
    for rx, key in COMPILED:
        if rx.search(u):
            return "опознан", key
    if not HAS_FORM.search(name):
        return "сотрудник/ФИО", None
    return "не опознан", None


